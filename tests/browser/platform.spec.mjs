  await page.screenshot({path:"test-results/read-denied.png",fullPage:true});
  await page.getByRole("button",{name:"Close dialog"}).click();
  const creator="My Homes Creator "+Date.now();
  const creatorCard=await register(page,creator,"Create projects");
  await creatorCard.getByRole("button",{name:"View permissions & test access →"}).click();
  await page.getByLabel("Project name",{exact:true}).fill("Agent Created Cedar "+Date.now());
  await page.getByRole("button",{name:"Create project as agent",exact:true}).click();
  await expect(page.locator(".decision")).toContainText("Access allowed");
  await page.getByLabel("Target organization").selectOption("green-builders");
  await page.getByRole("button",{name:"Create project as agent",exact:true}).click();
  await expect(page.locator(".decision")).toContainText("Access denied");
  await page.getByRole("button",{name:"Close dialog"}).click();
  await page.getByRole("button",{name:"Projects",exact:true}).click();
  await page.getByRole("button",{name:"+ Create project",exact:true}).click();
  const delegatedProject="Delegated Cedar "+Date.now();
  await page.getByLabel("Project name",{exact:true}).fill(delegatedProject);
  await page.getByLabel("Create as",{exact:true}).selectOption({label:creator+" · agent"});
  await page.getByRole("button",{name:"Create project",exact:true}).click();
  await expect(page.getByRole("heading",{name:delegatedProject,exact:true})).toBeVisible();
  await expect(page.locator(".project-card").filter({has:page.getByRole("heading",{name:delegatedProject,exact:true})})).toContainText(creator);
  await page.getByRole("button",{name:"Permissions",exact:true}).click();
  await expect(page.getByRole("cell",{name:"Sunrise Towers",exact:true}).first()).toBeVisible();
  await page.screenshot({path:"test-results/permissions.png",fullPage:true});
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await page.reload();
  await expect(page.getByRole("heading",{name:"Sign in to Northstar"})).toBeVisible();

  await login(page,"Meera Nair");
  await expect(page.getByRole("heading",{name:"Sunrise Towers",exact:true})).toHaveCount(0);
  await expect(page.getByRole("heading",{name:"Green Heights",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"+ Create project",exact:true}).click();
  await page.getByLabel("Project name",{exact:true}).fill("Green Gardens "+Date.now());
  await page.getByRole("button",{name:"Create project",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Green Builders");
  const greenCard=await register(page,"Green Builders Creator "+Date.now(),"Create projects");
  await greenCard.getByRole("button",{name:"View permissions & test access →"}).click();
  await page.getByRole("button",{name:"Create project as agent",exact:true}).click();
  await expect(page.locator(".decision")).toContainText("Access allowed");
  await page.getByLabel("Target organization").selectOption("my-homes");
  await page.getByRole("button",{name:"Create project as agent",exact:true}).click();
  await expect(page.locator(".decision")).toContainText("Access denied");
  await page.getByRole("button",{name:"Close dialog"}).click();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
