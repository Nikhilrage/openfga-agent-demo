  const reader="Sunrise Assistant "+Date.now();
  const card=await register(page,reader,"Read projects","Sunrise Towers");
  await card.getByRole("button",{name:"View permissions & test access →"}).click();
  await page.getByLabel("Project",{exact:true}).selectOption({label:"Sunrise Towers · assigned"});
  await page.getByRole("button",{name:"Read project",exact:true}).click();
